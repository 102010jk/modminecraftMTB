def boards(seed, wood=WOODD, nails=True):
    f = 0.6 * noise(seed, cells=(2, 8), octaves=2) + 0.25 * noise(seed + 1, cells=(1, 16), octaves=1) + 0.15 * white(seed)
    idx = quantize(f, gauss_weights(8, .55, .2))
    rng = np.random.default_rng(seed)
    nail = np.zeros((S, S), bool)
    nidx = np.zeros((S, S), int)
    joints = [11, 4, 14, 7]
    for b in range(4):
        y0 = b * 4
        idx[y0:y0 + 3] += int(rng.integers(-1, 2))
        idx[y0, :] += 1
        idx[y0 + 3, :] = 1
        j = joints[b]
        idx[y0:y0 + 3, j] = 2
        idx[y0:y0 + 3, (j + 1) % 16] += 1
        if nails:
            for nx in ((j - 2) % 16, (j + 3) % 16):
                nail[y0 + 1, nx] = True
                nidx[y0 + 1, nx] = 2
                nail[y0 + 2, nx] = True
                nidx[y0 + 2, nx] = 0
    idx = cleanup(np.clip(idx, 0, 7), 0.35)
    return composite((wood, idx, None), (NAILR, nidx, nail))


