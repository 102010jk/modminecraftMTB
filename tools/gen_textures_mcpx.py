def iso_icon(top, side, height=1.0):
    """16x16 isometric block icon from block textures (top 100 %, left 80 %, right 62 %)."""
    out = np.zeros((S, S, 4), np.uint8)
    for y in range(S):
        for x in range(S):
            px, py = x + .5, y + .5
            sx = (px - 8) / 7.5
            col = None
            # top face at height h
            yt = py - (1 - height) * 8
            u, w = (sx + yt / 3.75) / 2, (yt / 3.75 - sx) / 2
            if 0 <= u < 1 and 0 <= w < 1:
                col = top[int(w * 16), int(u * 16)].astype(float)
            else:
                if sx <= 0:  # front-left face, w = 1
                    u = sx + 1
                    h = height - (py - 3.75 * (u + 1) - (1 - height) * 8) / 8
                    if 0 <= u < 1 and 0 <= h < height:
                        col = side[min(15, int((1 - h) * 16)), min(15, int(u * 16))].astype(float) * [.8, .8, .8, 1]
                else:        # front-right face, u = 1
                    w = 1 - sx
                    h = height - (py - 3.75 * (1 + w) - (1 - height) * 8) / 8
                    if 0 <= w < 1 and 0 <= h < height:
                        col = side[min(15, int((1 - h) * 16)), min(15, int((1 - w) * 16))].astype(float) * [.62, .62, .62, 1]
            if col is not None and col[3] > 0:
                out[y, x] = np.clip(col, 0, 255)
    return out


