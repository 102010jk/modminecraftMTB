def rubble(seed):
    cells, _ = voronoi(seed, points=8)
    rng = np.random.default_rng(seed + 1)
    tone = rng.integers(3, 6, 9)
    idx = tone[cells] + (white(seed + 2) > .8).astype(int) - (white(seed + 3) > .85).astype(int)
    joint = (cells != np.roll(cells, -1, 0)) | (cells != np.roll(cells, -1, 1))
    below = ((cells != np.roll(cells, 1, 0)) | (cells != np.roll(cells, 1, 1))) & ~joint
    idx[below] += 2
    idx[np.roll(joint, 1, 0) & ~joint & ~below] -= 1
    idx[joint] = 0
    idx[joint & (white(seed + 4) > .6)] = 1
    return np.clip(idx, 0, 7)


