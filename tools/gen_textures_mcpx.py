def part(art, ramp, **kw):
    """ASCII silhouette: '#' body (auto-shaded, outline on the rim), '*' brightest, '-' dark accent.
    '+' is plain body too (a fill of '+' would be a flat highlight - the 'flat fills' anti-pattern)."""
    m, ch = mask_from_ascii(art.replace('+', '#'))
    return ramp, shade_item(m, len(ramp), ch, **kw), m


def line(art, ramp, v):
    """1 px detail strokes (map trails, screen trace) at one shade - no outline."""
    m, _ = mask_from_ascii(art)
    return ramp, np.where(m, v, 0), m


